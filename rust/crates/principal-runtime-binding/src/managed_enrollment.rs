/// Privacy-safe error codes: no proof, key, session, nonce, or input is echoed.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EnrollmentProofError {
    InvalidPolicy,
    InvalidChallenge,
    InvalidJson,
    DuplicateJsonField,
    InvalidCompactJws,
    NonCanonicalEncoding,
    InvalidProtectedHeader,
    PayloadMismatch,
    InvalidPublicKey,
    KeyBindingMismatch,
    AlgorithmMismatch,
    InvalidSignature,
    NonCanonicalSignature,
    NotYetValid,
    Expired,
    ClockRegression,
}

