//! Versioned, implementation-specific proof of managed enrollment key possession.
//!
//! The host constructs and retains an [`EnrollmentChallenge`] from its own
//! authenticated administrator session, current directory state, random nonce,
//! deployment policy and clock. The signer signs the exact supplied payload in
//! the compact JWS profile documented in `docs/managed-enrollment-proof.md`.
//!
//! [`verify_enrollment_proof`] uses an independently loaded public key, not a key
//! supplied inside the proof. Successful verification has no replay-store side
//! effect. The host must lock and atomically consume the same retained challenge,
//! recheck administrator/session authorization, current key, revision and status,
//! and call [`VerifiedEnrollmentProof::ensure_current`] with a fresh commit clock.
//! Only then may it record enrollment key control. This is not a complete Machine
//! Authentication Policy appraisal, a workload attestation, or an authorization.

use std::fmt;

use base64::{engine::general_purpose::URL_SAFE_NO_PAD, Engine};
use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use serde_json::{json, Value};
use sha2::{Digest, Sha256};
use uuid::Uuid;

use crate::{
    model, strict_json, thumbprint, validation, BindingError, ErrorKind, HashBasis, KeyAlgorithm,
    ThumbprintEncoding, TypedThumbprint,
};

pub const ENROLLMENT_PROFILE: &str = "urn:marty:managed-key-enrollment:v1";
pub const ENROLLMENT_PURPOSE: &str = "ENROLL_MANAGED_KEY";
pub const ENROLLMENT_JWS_TYPE: &str = "marty-managed-enrollment+jws";
pub const ENROLLMENT_SESSION_PREFIX: &str = "urn:marty:session:sha256:";
pub const MAX_ENROLLMENT_AGE_SECONDS: u32 = 300;
pub const MAX_SAFE_JSON_INTEGER: u64 = 9_007_199_254_740_991;
pub const MAX_ENROLLMENT_PROOF_BYTES: usize = 16_384;
const MAX_PAYLOAD_BYTES: usize = 8_192;
const MAX_HEADER_BYTES: usize = 1_024;
const MAX_EPOCH_SECONDS: i64 = 253_402_300_799;

/// Only these signing algorithms belong to the version-one local profile.
#[derive(Clone, Copy, Debug, Deserialize, Serialize, PartialEq, Eq, PartialOrd, Ord)]
pub enum EnrollmentAlgorithm {
    ES256,
    EdDSA,
}

impl EnrollmentAlgorithm {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::ES256 => "ES256",
            Self::EdDSA => "EdDSA",
        }
    }

    fn matches_key(self, algorithm: KeyAlgorithm) -> bool {
        matches!(
            (self, algorithm),
            (Self::ES256, KeyAlgorithm::ES256)
                | (Self::EdDSA, KeyAlgorithm::EdDSA | KeyAlgorithm::Ed25519)
        )
    }
}

/// Deployment-selected enrollment policy, not an operational MAP document.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct EnrollmentPolicy {
    profile: String,
    revision: u64,
    allowed_algorithms: Vec<EnrollmentAlgorithm>,
    max_age_seconds: u32,
}

impl EnrollmentPolicy {
    pub fn new(
        profile: String,
        revision: u64,
        mut allowed_algorithms: Vec<EnrollmentAlgorithm>,
        max_age_seconds: u32,
    ) -> Result<Self, EnrollmentProofError> {
        validation::uri(&profile, 1024, true, "policy.profile")
            .map_err(|_| EnrollmentProofError::InvalidPolicy)?;
        allowed_algorithms.sort();
        if !(1..=MAX_SAFE_JSON_INTEGER).contains(&revision)
            || !(1..=MAX_ENROLLMENT_AGE_SECONDS).contains(&max_age_seconds)
            || allowed_algorithms.is_empty()
            || allowed_algorithms.windows(2).any(|pair| pair[0] == pair[1])
        {
            return Err(EnrollmentProofError::InvalidPolicy);
        }
        Ok(Self {
            profile,
            revision,
            allowed_algorithms,
            max_age_seconds,
        })
    }

    pub fn profile(&self) -> &str {
        &self.profile
    }
    pub const fn revision(&self) -> u64 {
        self.revision
    }
    pub fn allowed_algorithms(&self) -> &[EnrollmentAlgorithm] {
        &self.allowed_algorithms
    }
    pub const fn max_age_seconds(&self) -> u32 {
        self.max_age_seconds
    }
    pub fn document(&self) -> Value {
        json!({
            "profile": self.profile,
            "revision": self.revision,
            "allowed_algorithms": self.allowed_algorithms,
            "max_age_seconds": self.max_age_seconds,
        })
    }
    pub fn digest(&self) -> String {
        digest(&canonical_json(&self.document()))
    }
}

/// All values come from trusted host configuration/state, never a proof body.
///
/// `nonce` must be 32 bytes freshly generated by a cryptographic random source.
/// `session_ref` is a SHA-256 digest of the authenticated human session identity,
/// in `urn:marty:session:sha256:<64 lowercase hex>` form, never a raw token.
/// `expected_revision` reserves the next exact JSON-safe integer for the result.
#[derive(Clone)]
pub struct EnrollmentChallengeParameters {
    pub challenge_id: Uuid,
    pub organization_id: Uuid,
    pub agent_id: Uuid,
    pub key_id: Uuid,
    pub administrator_id: Uuid,
    pub expected_revision: u64,
    pub key_algorithm: EnrollmentAlgorithm,
    pub key_thumbprint: TypedThumbprint,
    pub runtime_instance_ref: String,
    pub issuer: String,
    pub subject: String,
    pub session_ref: String,
    pub audience: String,
    pub nonce: [u8; 32],
    pub issued_at: i64,
    pub expires_at: i64,
    pub policy: EnrollmentPolicy,
}

/// Retained server challenge. Parsing a document does not authenticate its source.
#[derive(Clone)]
pub struct EnrollmentChallenge {
    parameters: EnrollmentChallengeParameters,
    document: Value,
    payload: Vec<u8>,
}

impl EnrollmentChallenge {
    pub fn new(
        mut parameters: EnrollmentChallengeParameters,
    ) -> Result<Self, EnrollmentProofError> {
        let p = &parameters;
        if [
            p.challenge_id,
            p.organization_id,
            p.agent_id,
            p.key_id,
            p.administrator_id,
        ]
        .iter()
        .any(Uuid::is_nil)
            || !(1..MAX_SAFE_JSON_INTEGER).contains(&p.expected_revision)
            || p.key_thumbprint.basis() != HashBasis::JwkRfc7638Sha256
            || p.nonce == [0; 32]
            || !valid_session_ref(&p.session_ref)
            || !(1..=512).contains(&p.subject.chars().count())
            || p.subject.chars().any(char::is_control)
            || !(0..=MAX_EPOCH_SECONDS).contains(&p.issued_at)
            || !(0..=MAX_EPOCH_SECONDS).contains(&p.expires_at)
            || p.expires_at <= p.issued_at
            || p.expires_at - p.issued_at > i64::from(p.policy.max_age_seconds)
        {
            return Err(EnrollmentProofError::InvalidChallenge);
        }
        for value in [&p.runtime_instance_ref, &p.issuer, &p.audience] {
            validation::uri(value, 1024, true, "challenge.uri")
                .map_err(|_| EnrollmentProofError::InvalidChallenge)?;
        }
        if !p.policy.allowed_algorithms.contains(&p.key_algorithm) {
            return Err(EnrollmentProofError::AlgorithmMismatch);
        }
        parameters.key_thumbprint = parameters
            .key_thumbprint
            .reencode(ThumbprintEncoding::Base64urlSha256);
        let p = &parameters;
        let document = json!({
            "profile": ENROLLMENT_PROFILE,
            "purpose": ENROLLMENT_PURPOSE,
            "challenge_id": p.challenge_id.to_string(),
            "organization_id": p.organization_id.to_string(),
            "agent_id": p.agent_id.to_string(),
            "key_id": p.key_id.to_string(),
            "expected_revision": p.expected_revision,
            "key_algorithm": p.key_algorithm,
            "key_thumbprint": {
                "basis": "JWK_RFC7638_SHA256",
                "encoding": "BASE64URL_SHA256",
                "value": p.key_thumbprint.encoded_value(),
            },
            "runtime_instance_ref": p.runtime_instance_ref,
            "issuer": p.issuer,
            "subject": p.subject,
            "administrator_id": p.administrator_id.to_string(),
            "session_ref": p.session_ref,
            "audience": p.audience,
            "nonce": URL_SAFE_NO_PAD.encode(p.nonce),
            "iat": p.issued_at,
            "exp": p.expires_at,
            "policy": p.policy.document(),
        });
        let payload = canonical_json(&document);
        if payload.len() > MAX_PAYLOAD_BYTES {
            return Err(EnrollmentProofError::InvalidChallenge);
        }
        Ok(Self {
            parameters,
            document,
            payload,
        })
    }

    /// Reconstruct exclusively from a host-owned retained document, such as the
    /// challenge row locked during completion. Never pass request-supplied JSON.
    /// JSONB whitespace/key ordering may differ; all values must be canonical.
    pub fn from_trusted_document(raw: &[u8]) -> Result<Self, EnrollmentProofError> {
        if raw.len() > MAX_PAYLOAD_BYTES * 2 {
            return Err(EnrollmentProofError::InvalidChallenge);
        }
        let document = strict_json::object(raw).map_err(json_error)?;
        let parsed: ChallengeDocument = serde_json::from_value(document.clone())
            .map_err(|_| EnrollmentProofError::InvalidChallenge)?;
        if parsed.profile != ENROLLMENT_PROFILE || parsed.purpose != ENROLLMENT_PURPOSE {
            return Err(EnrollmentProofError::InvalidChallenge);
        }
        let policy = EnrollmentPolicy::new(
            parsed.policy.profile,
            parsed.policy.revision,
            parsed.policy.allowed_algorithms,
            parsed.policy.max_age_seconds,
        )?;
        let restored = Self::new(EnrollmentChallengeParameters {
            challenge_id: parsed.challenge_id,
            organization_id: parsed.organization_id,
            agent_id: parsed.agent_id,
            key_id: parsed.key_id,
            administrator_id: parsed.administrator_id,
            expected_revision: parsed.expected_revision,
            key_algorithm: parsed.key_algorithm,
            key_thumbprint: TypedThumbprint::from_document(&parsed.key_thumbprint)
                .map_err(|_| EnrollmentProofError::InvalidChallenge)?,
            runtime_instance_ref: parsed.runtime_instance_ref,
            issuer: parsed.issuer,
            subject: parsed.subject,
            session_ref: parsed.session_ref,
            audience: parsed.audience,
            nonce: thumbprint::decode_b64(&parsed.nonce, "challenge.nonce")
                .map_err(|_| EnrollmentProofError::InvalidChallenge)?,
            issued_at: parsed.iat,
            expires_at: parsed.exp,
            policy,
        })?;
        if restored.document != document {
            return Err(EnrollmentProofError::InvalidChallenge);
        }
        Ok(restored)
    }

    pub fn payload(&self) -> &[u8] {
        &self.payload
    }
    pub fn payload_b64url(&self) -> String {
        URL_SAFE_NO_PAD.encode(&self.payload)
    }
    pub fn document(&self) -> Value {
        self.document.clone()
    }
    pub fn digest(&self) -> String {
        digest(&self.payload)
    }
    pub fn policy_digest(&self) -> String {
        self.parameters.policy.digest()
    }
    pub fn policy(&self) -> &EnrollmentPolicy {
        &self.parameters.policy
    }
    pub const fn challenge_id(&self) -> Uuid {
        self.parameters.challenge_id
    }
    pub const fn organization_id(&self) -> Uuid {
        self.parameters.organization_id
    }
    pub const fn agent_id(&self) -> Uuid {
        self.parameters.agent_id
    }
    pub const fn key_id(&self) -> Uuid {
        self.parameters.key_id
    }
    pub const fn administrator_id(&self) -> Uuid {
        self.parameters.administrator_id
    }
    pub const fn expected_revision(&self) -> u64 {
        self.parameters.expected_revision
    }
    pub const fn key_algorithm(&self) -> EnrollmentAlgorithm {
        self.parameters.key_algorithm
    }
    pub fn key_thumbprint(&self) -> &TypedThumbprint {
        &self.parameters.key_thumbprint
    }
    pub fn session_ref(&self) -> &str {
        &self.parameters.session_ref
    }
    pub fn audience(&self) -> &str {
        &self.parameters.audience
    }
    pub const fn issued_at(&self) -> i64 {
        self.parameters.issued_at
    }
    pub const fn expires_at(&self) -> i64 {
        self.parameters.expires_at
    }

    fn ensure_current(&self, now: DateTime<Utc>) -> Result<(), EnrollmentProofError> {
        // Compare the complete clock value: a proof at exactly exp is expired.
        if now < DateTime::from_timestamp(self.issued_at(), 0).expect("validated timestamp") {
            return Err(EnrollmentProofError::NotYetValid);
        }
        if now >= DateTime::from_timestamp(self.expires_at(), 0).expect("validated timestamp") {
            return Err(EnrollmentProofError::Expired);
        }
        Ok(())
    }
}

/// Successful purpose-specific verification. Not cloneable, deserializable or a
/// bearer capability; the host must consume this by value in its own transaction.
///
/// ```compile_fail
/// use marty_principal_runtime_binding::managed_enrollment::VerifiedEnrollmentProof;
/// let forged: VerifiedEnrollmentProof = serde_json::from_str("{}").unwrap();
/// ```
///
/// ```compile_fail
/// use marty_principal_runtime_binding::managed_enrollment::VerifiedEnrollmentProof;
/// fn duplicate(proof: VerifiedEnrollmentProof) { let _ = proof.clone(); }
/// ```
pub struct VerifiedEnrollmentProof {
    challenge: EnrollmentChallenge,
    proof_digest: String,
    verified_at: DateTime<Utc>,
}

impl VerifiedEnrollmentProof {
    pub const fn challenge_id(&self) -> Uuid {
        self.challenge.challenge_id()
    }
    pub const fn organization_id(&self) -> Uuid {
        self.challenge.organization_id()
    }
    pub const fn agent_id(&self) -> Uuid {
        self.challenge.agent_id()
    }
    pub const fn key_id(&self) -> Uuid {
        self.challenge.key_id()
    }
    pub const fn expected_revision(&self) -> u64 {
        self.challenge.expected_revision()
    }
    pub fn key_thumbprint(&self) -> &TypedThumbprint {
        self.challenge.key_thumbprint()
    }
    pub fn proof_digest(&self) -> &str {
        &self.proof_digest
    }
    pub fn payload_digest(&self) -> String {
        self.challenge.digest()
    }
    pub fn policy_digest(&self) -> String {
        self.challenge.policy_digest()
    }
    pub const fn verified_at(&self) -> DateTime<Utc> {
        self.verified_at
    }
    /// Recheck with a fresh host clock while holding the challenge/current-key
    /// locks, before the atomic consume. A backwards clock is rejected as well.
    pub fn ensure_current(&self, now: DateTime<Utc>) -> Result<(), EnrollmentProofError> {
        if now < self.verified_at {
            return Err(EnrollmentProofError::ClockRegression);
        }
        self.challenge.ensure_current(now)
    }
}

